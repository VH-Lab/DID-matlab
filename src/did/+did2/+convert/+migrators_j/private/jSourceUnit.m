function [term, factor, kind, slot] = jSourceUnit(spelling)
%JSOURCEUNIT A v1 unit spelling as a `source_unit` term, and its factor to the
%   canonical unit of its value kind.
%
%   [TERM, FACTOR, KIND, SLOT] = jSourceUnit(SPELLING). did-schema #88 makes
%   `source_unit` a bound ontology_term (V_eta_source_unit_plan.md, signed
%   2026-10-21). Item 4, for migrated data: "a v1 unit spelling is mapped to a
%   registered term; a spelling no term matches is kept as the term's `name`
%   with an empty `node`, and the migration reports it. It is not dropped and
%   not guessed." So:
%
%     - a spelling in the table below whose term the registry holds -> that
%       term (om:millisecond-Time, ...);
%     - any other non-empty spelling -> {node '', name SPELLING}; the
%       unregistered-term collector in did2.convert.v1_to_v2 reports it;
%     - '' -> [] (no source unit, no term).
%
%   FACTOR multiplies a source value into the canonical unit of KIND
%   (volts, seconds, meters, grams, hertz, degrees, celsius, liters, amperes,
%   molar),
%   or is [] when the spelling is not one this table knows -- the caller then
%   writes no canonical value rather than a guessed one. KIND is '' then.
%
%   Every row of the table names a unit the term registry holds (volt,
%   millivolt, microvolt, kilogram, kilohertz, ampere and its multiples were
%   registered after hertz, degree and radian) and is written with the
%   registry's node and name. A spelling in the second table (dB -> om:decibel)
%   is registered but has no canonical factor here: it gets its term, FACTOR []
%   and KIND '' (so no canonical value is computed from it, as before).
%
%   CONCENTRATION. A `concentration` cell has several canonical slots (molar,
%   grams_per_liter, liters_per_liter, ...), so its rows are a table of their
%   own, CONC below, that says each row's SLOT: the canonical field FACTOR
%   converts into (jQuantity, jDoseBodies write the value there). SLOT is ''
%   for every other kind (one canonical field each). The MOLAR rows (om:molar,
%   [molar kept], Jess Haley, 2026-10-22) are the
%   spellings NDI's v1 writers use: every mixture_table writer on NDI-matlab
%   (+birren/TreatmentCreator.m, +birren/createSayaTreatments.m,
%   +babu/treatments.json, +marder/marder_mixtures.json,
%   +birren/birren_mixtures.txt) writes unitName 'Molar', with the value
%   already in molar (CNO 10e-6, hexamethonium 100e-6); 'molar' is the
%   registry's label and 'M' the SI symbol. They are added so a molar
%   concentration gets its canonical, which [canonical absent only as needs
%   info] (Jess Haley, 2026-10-30) requires, instead of being carried as
%   carry-155 ("resolved_by: ... a new row in the unit table").
%   mM, uM, nM and pM are exact too but NOT here: om:millimolar,
%   om:micromolar, om:nanomolar and om:picomolar are not in the term registry,
%   and a row names a registered term (registry row first); no v1 writer
%   writes them. Until then they are unrecognised (carry-155 where a caller
%   carries).
%
%   PERCENT VOLUME PER VOLUME (slot liters_per_liter, factor 0.01): Babu's
%   treatments (NDI-matlab +babu/treatments.json, unitName 'Percent Volume per
%   Volume', ontologyUnit NCIT:C48571) state a volume fraction in percent;
%   x0.01 is liters per liter exactly. Decided by Jess Haley, 2026-11-01
%   [percent volume per volume converted] (did-schema
%   did_v2_go_forward_class_audit.md; docs/V2_PLAN.md G72: "add [NCIT:C48571
%   Percent Volume per Volume] to the registry and convert it ... x0.01 to
%   concentration.liters_per_liter"; "Ok, keep liters_per_liter").

term = [];
factor = [];
kind = '';
slot = '';
if isstring(spelling); spelling = char(spelling); end
if ~ischar(spelling) || isempty(strtrim(spelling))
    return;
end
s = strtrim(spelling);
% spelling            kind          factor        registered node, label
T = { ...
    'V',              'voltage',    1,            'om:volt', 'volt'; ...
    'volt',           'voltage',    1,            'om:volt', 'volt'; ...
    'volts',          'voltage',    1,            'om:volt', 'volt'; ...
    'mV',             'voltage',    1e-3,         'om:millivolt', 'millivolt'; ...
    'millivolt',      'voltage',    1e-3,         'om:millivolt', 'millivolt'; ...
    'uV',             'voltage',    1e-6,         'om:microvolt', 'microvolt'; ...
    [char(181) 'V'],  'voltage',    1e-6,         'om:microvolt', 'microvolt'; ...
    'microvolt',      'voltage',    1e-6,         'om:microvolt', 'microvolt'; ...
    's',              'time',       1,            'om:second-Time', 'second'; ...
    'sec',            'time',       1,            'om:second-Time', 'second'; ...
    'second',         'time',       1,            'om:second-Time', 'second'; ...
    'seconds',        'time',       1,            'om:second-Time', 'second'; ...
    'ms',             'time',       1e-3,         'om:millisecond-Time', 'millisecond'; ...
    'millisecond',    'time',       1e-3,         'om:millisecond-Time', 'millisecond'; ...
    'milliseconds',   'time',       1e-3,         'om:millisecond-Time', 'millisecond'; ...
    'us',             'time',       1e-6,         'om:microsecond-Time', 'microsecond'; ...
    'ns',             'time',       1e-9,         'om:nanosecond-Time', 'nanosecond'; ...
    'min',            'time',       60,           'om:minute-Time', 'minute'; ...
    'minute',         'time',       60,           'om:minute-Time', 'minute'; ...
    'minutes',        'time',       60,           'om:minute-Time', 'minute'; ...
    'h',              'time',       3600,         'om:hour', 'hour'; ...
    'hr',             'time',       3600,         'om:hour', 'hour'; ...
    'hour',           'time',       3600,         'om:hour', 'hour'; ...
    'hours',          'time',       3600,         'om:hour', 'hour'; ...
    'm',              'length',     1,            'om:metre', 'metre'; ...
    'meter',          'length',     1,            'om:metre', 'metre'; ...
    'metre',          'length',     1,            'om:metre', 'metre'; ...
    'cm',             'length',     1e-2,         'om:centimetre', 'centimetre'; ...
    'mm',             'length',     1e-3,         'om:millimetre', 'millimetre'; ...
    'millimeter',     'length',     1e-3,         'om:millimetre', 'millimetre'; ...
    'um',             'length',     1e-6,         'om:micrometre', 'micrometre'; ...
    [char(181) 'm'],  'length',     1e-6,         'om:micrometre', 'micrometre'; ...
    'micron',         'length',     1e-6,         'om:micrometre', 'micrometre'; ...
    'microns',        'length',     1e-6,         'om:micrometre', 'micrometre'; ...
    'micrometer',     'length',     1e-6,         'om:micrometre', 'micrometre'; ...
    'nm',             'length',     1e-9,         'om:nanometre', 'nanometre'; ...
    'g',              'mass',       1,            'om:gram', 'gram'; ...
    'gram',           'mass',       1,            'om:gram', 'gram'; ...
    'grams',          'mass',       1,            'om:gram', 'gram'; ...
    'mg',             'mass',       1e-3,         'om:milligram', 'milligram'; ...
    'kg',             'mass',       1e3,          'om:kilogram', 'kilogram'; ...
    'Hz',             'frequency',  1,            'om:hertz', 'hertz'; ...
    'hz',             'frequency',  1,            'om:hertz', 'hertz'; ...
    'kHz',            'frequency',  1e3,          'om:kilohertz', 'kilohertz'; ...
    'deg',            'angle',      1,            'om:degree', 'degree'; ...
    'degree',         'angle',      1,            'om:degree', 'degree'; ...
    'degrees',        'angle',      1,            'om:degree', 'degree'; ...
    'rad',            'angle',      180/pi,       'om:radian', 'radian'; ...
    'radian',         'angle',      180/pi,       'om:radian', 'radian'; ...
    'radians',        'angle',      180/pi,       'om:radian', 'radian'; ...
    'C',              'temperature',1,            'om:degreeCelsius', 'degree Celsius'; ...
    'degC',           'temperature',1,            'om:degreeCelsius', 'degree Celsius'; ...
    'celsius',        'temperature',1,            'om:degreeCelsius', 'degree Celsius'; ...
    'L',              'volume',     1,            'om:litre', 'litre'; ...
    'l',              'volume',     1,            'om:litre', 'litre'; ...
    'mL',             'volume',     1e-3,         'om:millilitre', 'millilitre'; ...
    'ml',             'volume',     1e-3,         'om:millilitre', 'millilitre'; ...
    'uL',             'volume',     1e-6,         'om:microlitre', 'microlitre'; ...
    'ul',             'volume',     1e-6,         'om:microlitre', 'microlitre'; ...
    'A',              'current',    1,            'om:ampere', 'ampere'; ...
    'mA',             'current',    1e-3,         'om:milliampere', 'milliampere'; ...
    'uA',             'current',    1e-6,         'om:microampere', 'microampere'; ...
    'nA',             'current',    1e-9,         'om:nanoampere', 'nanoampere'; ...
    'pA',             'current',    1e-12,        'om:picoampere', 'picoampere'};
% concentration rows: the table says each row's canonical slot
% spelling                     slot                factor  registered node, label
CONC = { ...
    'M',                         'molar',            1,      'om:molar', 'molar'; ...
    'Molar',                     'molar',            1,      'om:molar', 'molar'; ...
    'molar',                     'molar',            1,      'om:molar', 'molar'; ...
    'Percent Volume per Volume', 'liters_per_liter', 0.01,   'NCIT:C48571', 'Percent Volume per Volume'};
% registered spellings with no canonical factor in this table
% spelling            registered node, label
TERMONLY = { ...
    'dB',             'om:decibel', 'decibel'};
hitC = find(strcmp(CONC(:, 1), s), 1);
if ~isempty(hitC)
    kind = 'concentration';
    [slot, factor] = CONC{hitC, 2:3};
    term = did2.build.term(CONC{hitC, 4}, CONC{hitC, 5});
    return;
end
hit = find(strcmp(T(:, 1), s), 1);
if isempty(hit)
    hitT = find(strcmp(TERMONLY(:, 1), s), 1);
    if isempty(hitT)
        term = did2.build.term('', s);
    else
        term = did2.build.term(TERMONLY{hitT, 2}, TERMONLY{hitT, 3});
    end
    return;
end
kind = T{hit, 2};
factor = T{hit, 3};
if isempty(T{hit, 4})
    term = did2.build.term('', s);
else
    term = did2.build.term(T{hit, 4}, T{hit, 5});
end
end
